// 边界表述的同义说法。答复校验（guard）和评测判定（runner）共用这一份，
// 避免"校验放行了、判定却不认"或反过来的口径不一致。
// 只收语义等价的说法；系统给出的事实（金额、状态、原因、路径）不在这里，必须逐字保留。
const GROUPS = [
  ['不能', '无法', '没法'],
  ['没法承诺', '无法承诺', '不能承诺'],
  ['无法核实', '没法核实', '不能核实'],
  ['不推测', '不猜测', '无法核实', '不做推测'],
  ['不要', '请勿', '切勿'],
  ['不需要重复提交', '无需重复提交', '不用重复提交', '不必重复提交'],
  ['不要重复提交', '请勿重复提交', '切勿重复提交'],
  ['没有成功', '未能成功', '未成功'],
  ['重新验证', '完成身份验证', '重新完成验证'],
  ['暂未找到', '暂时没有找到', '暂时未找到'],
];
const ALT = Object.fromEntries(GROUPS.map(g => [g[0], g]));
export const altsOf = k => Array.isArray(k) ? k : (ALT[k] || [k]);
export const hasPhrase = (text, k) => altsOf(k).some(a => text.includes(a));
